<h1>About Me</h1>

<p>Hi, I'm Sam.</p>

<p>I built this corner of the internet to share my projects, thoughts, and experiments. Right now, this site is running on a self-hosted architecture—SvelteKit compiled to a Node server, managed by PM2, and deployed via a secure Cloudflare Tunnel from my home network.</p>

<p>I believe in keeping the web simple, fast, and personal. If you're reading this, it means the stack is holding up perfectly.</p>

<h2>What I do</h2>
<p>I enjoy tinkering with new web technologies, automating workflows, and exploring how tools like LLMs can change the way we build software. In fact, this blog itself was spun up using an entirely agentic workflow.</p>

